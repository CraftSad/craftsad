export function formatDate(iso: string): string {
  const [year, month, day] = iso.split("-");
  const months = [
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
  ];
  return `${Number(day)} ${months[Number(month) - 1] ?? month} ${year}`;
}

